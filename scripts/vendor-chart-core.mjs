#!/usr/bin/env node
/**
 * Copies the sources of the shared package packages/chart-core into functions/src/vendor/chart-core.
 *
 * Why: `firebase deploy` uploads the folder `functions/` only, so a workspace package that lives
 * outside it is missing in Cloud Build. The functions build compiles this generated copy into
 * `functions/lib`, which is what the deploy uploads. The copy is git-ignored and rebuilt by the
 * `prebuild`, `prelint` and `pretest` scripts of the functions workspace; never edit it by hand.
 *
 * Tests (`__tests__`) and non-TypeScript files are not copied. Output is deterministic: the target is
 * wiped first, files are written in sorted order and carry a fixed header.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(repoRoot, "packages", "chart-core", "src");
const targetDir = join(repoRoot, "functions", "src", "vendor", "chart-core");

const HEADER =
  "// GENERATED by scripts/vendor-chart-core.mjs from packages/chart-core/src. Do not edit: changes are overwritten.\n";

/** Sorted list of the TypeScript sources under `dir`, relative to `dir`, without test folders. */
function listSources(dir, prefix = "") {
  const entries = readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
  const files = [];
  for (const entry of entries) {
    if (entry.name === "__tests__") continue;
    const rel = join(prefix, entry.name);
    if (entry.isDirectory()) files.push(...listSources(join(dir, entry.name), rel));
    else if (entry.name.endsWith(".ts")) files.push(rel);
  }
  return files;
}

const files = listSources(sourceDir);
if (files.length === 0) {
  console.error(`vendor-chart-core: no sources found in ${relative(repoRoot, sourceDir)}`);
  process.exit(1);
}

rmSync(targetDir, { recursive: true, force: true });
for (const file of files) {
  const target = join(targetDir, file);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, HEADER + readFileSync(join(sourceDir, file), "utf-8"));
}
console.log(`vendor-chart-core: ${files.length} files -> ${relative(repoRoot, targetDir)}`);
